"""Deadline calendar reminder (.ics) generator for NoticeWise (F7).

Generates standard iCalendar (.ics) files with:
- All-day deadline event on the due date.
- Formatted summary and description with procedural checklist.
- Standard VALARM notification 3 days prior to the deadline.
- Full RFC 5545 compliance for importing into Google Calendar, Apple Calendar, Outlook.
"""

import uuid
from datetime import date, datetime, timedelta
from typing import Optional

from src.schemas import DocumentType, NoticeExtraction, ReminderInfo


def compute_days_left(deadline_date_str: Optional[str], as_of_date: Optional[date] = None) -> Optional[int]:
    """Calculate integer days remaining until deadline using local system date or reference date.

    Always computed in Python, never by an LLM.
    Returns:
        Integer number of days remaining (can be negative if overdue), or None if date is unset.
    """
    if not deadline_date_str:
        return None
    try:
        deadline = datetime.strptime(deadline_date_str, "%Y-%m-%d").date()
        ref = as_of_date if as_of_date is not None else date.today()
        return (deadline - ref).days
    except ValueError:
        return None


def create_reminder_payload(extraction: NoticeExtraction) -> Optional[ReminderInfo]:
    """Construct ReminderInfo metadata from extracted notice fields."""
    if not extraction.deadline_date:
        return None

    try:
        due = datetime.strptime(extraction.deadline_date, "%Y-%m-%d").date()
    except ValueError:
        return None

    reminder_dt = due - timedelta(days=3)
    doc_type_label = (
        extraction.doc_type.value
        if hasattr(extraction.doc_type, "value")
        else str(extraction.doc_type)
    ).replace("_", " ").title()

    title = f"NoticeWise: Action Due for {doc_type_label} Notice"
    if extraction.reference_number:
        title += f" ({extraction.reference_number})"

    desc_lines = [
        f"NoticeWise Deadline Reminder for {doc_type_label}",
        f"Issuer: {extraction.issuer or 'Official Authority'}",
        f"Reference Number: {extraction.reference_number or 'N/A'}",
        f"Due Date: {extraction.deadline_date}",
    ]
    if extraction.amount_inr is not None:
        desc_lines.append(f"Amount Involved: INR {extraction.amount_inr:,.2f}")

    desc_lines.append("")
    desc_lines.append("Urgent Action Required:")
    desc_lines.append("- Verify requirements and submit your dispute, application, or payment.")
    desc_lines.append("- Ensure all cited documents and copies are attached.")
    desc_lines.append("- Generated by NoticeWise (Civic Pulse digital governance assistant).")

    return ReminderInfo(
        title=title,
        description="\n".join(desc_lines),
        due_date=extraction.deadline_date,
        reminder_date=reminder_dt.strftime("%Y-%m-%d"),
        issuer=extraction.issuer,
        reference_number=extraction.reference_number,
    )


def generate_ics_calendar(
    reminder_info: ReminderInfo,
    alarm_days_before: int = 3,
) -> str:
    """Generate a standard RFC 5545 iCalendar (.ics) string.

    Args:
        reminder_info: Structured reminder metadata.
        alarm_days_before: Number of days before deadline to trigger VALARM notification (default 3).

    Returns:
        String containing valid .ics file contents.
    """
    # Parse deadline date
    due_date_clean = reminder_info.due_date.replace("-", "")
    due_dt = datetime.strptime(reminder_info.due_date, "%Y-%m-%d").date()
    # For all-day event, DTEND is exclusive (day after due date)
    end_dt = due_dt + timedelta(days=1)
    end_date_clean = end_dt.strftime("%Y%m%d")

    now_utc = datetime.utcnow().strftime("%Y%m%dT%H%M%SZ")
    uid = f"{uuid.uuid4()}@noticewise.civic"

    # Escape iCalendar text fields
    def escape_text(text: str) -> str:
        return (
            text.replace("\\", "\\\\")
            .replace(";", "\\;")
            .replace(",", "\\,")
            .replace("\n", "\\n")
        )

    summary_escaped = escape_text(reminder_info.title)
    desc_escaped = escape_text(reminder_info.description)

    ics_content = f"""BEGIN:VCALENDAR
VERSION:2.0
PRODID:-//NoticeWise//Civic Governance Reminder 1.0//EN
CALSCALE:GREGORIAN
METHOD:PUBLISH
BEGIN:VEVENT
UID:{uid}
DTSTAMP:{now_utc}
DTSTART;VALUE=DATE:{due_date_clean}
DTEND;VALUE=DATE:{end_date_clean}
SUMMARY:{summary_escaped}
DESCRIPTION:{desc_escaped}
STATUS:CONFIRMED
TRANSP:TRANSPARENT
BEGIN:VALARM
TRIGGER:-P{alarm_days_before}D
ACTION:DISPLAY
DESCRIPTION:Reminder: NoticeWise deadline in {alarm_days_before} days
END:VALARM
END:VEVENT
END:VCALENDAR"""

    return ics_content.strip() + "\r\n"


def generate_ics_from_extraction(
    extraction: NoticeExtraction,
    alarm_days_before: int = 3,
) -> Optional[str]:
    """Convenience helper generating .ics file content directly from a NoticeExtraction.

    Returns:
        .ics file content string, or None if extraction lacks a valid deadline_date.
    """
    payload = create_reminder_payload(extraction)
    if not payload:
        return None
    return generate_ics_calendar(payload, alarm_days_before=alarm_days_before)
